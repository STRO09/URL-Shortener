SET SERVEROUTPUT ON;

-- Create URL_MAPPING table with Oracle-native identity column and constraints
-- Supports Oracle 23ai/26ai IF NOT EXISTS syntax, with PL/SQL fallback
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE IF NOT EXISTS URL_MAPPING (
            id          NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
            longurl     VARCHAR2(2048) NOT NULL,
            shortcode   VARCHAR2(15)   NOT NULL,
            created_at  TIMESTAMP(6)   NOT NULL,
            expires_at  TIMESTAMP(6)   NOT NULL,
            click_count NUMBER(10,0)   DEFAULT 0,
            CONSTRAINT pk_url_mapping PRIMARY KEY (id),
            CONSTRAINT uk_url_mapping_longurl UNIQUE (longurl),
            CONSTRAINT uk_url_mapping_shortcode UNIQUE (shortcode)
        )
    ';
    DBMS_OUTPUT.PUT_LINE('Table URL_MAPPING verified/created successfully.');
EXCEPTION
    WHEN OTHERS THEN
        -- Fallback if IF NOT EXISTS is not supported in the connected environment
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Table URL_MAPPING already exists.');
        ELSE
            RAISE;
        END IF;
END;
/

-- Add descriptive comments for schema clarity
COMMENT ON TABLE URL_MAPPING IS 'Stores shortened URLs, aliases, expiration dates, and click metrics';
COMMENT ON COLUMN URL_MAPPING.id IS 'Surrogate primary key (generated identity)';
COMMENT ON COLUMN URL_MAPPING.longurl IS 'Destination URL to redirect to';
COMMENT ON COLUMN URL_MAPPING.shortcode IS 'Shortened identifier code or custom alias (up to 15 chars)';
COMMENT ON COLUMN URL_MAPPING.created_at IS 'Timestamp when the short URL was created';
COMMENT ON COLUMN URL_MAPPING.expires_at IS 'Timestamp when the short URL expires (default 1 month)';
COMMENT ON COLUMN URL_MAPPING.click_count IS 'Total click count / redirect hits';

PROMPT Table URL_MAPPING DDL executed.
